# tools/gen-shell-version.ps1 - writes shell_version.h at build time.
#
# Version = a tag on HEAD when one exists, otherwise the first 6 chars of the
# commit hash; append -dirty when the working tree has changes. The search-engine
# attribution parameter in the new tab page uses it (see main.c).
#
#   pwsh -File tools/gen-shell-version.ps1 -OutFile build/generated/shell_version.h -RepoRoot .
param(
    [Parameter(Mandatory = $true)][string]$OutFile,
    [Parameter(Mandatory = $true)][string]$RepoRoot
)

$ErrorActionPreference = 'Stop'

# git.exe, not `git`: a function called Git would win over the command and
# recurse forever in PowerShell's command resolution.
function Run-Git([string[]]$arguments)
{
    $output = & git.exe -C $RepoRoot @arguments 2>$null
    if ($LASTEXITCODE -ne 0) { return $null }
    return ($output -join "`n").Trim()
}

$version = $null

$tag = Run-Git @('describe', '--tags', '--exact-match', 'HEAD')
if ($tag) {
    $version = $tag
} else {
    $hash = Run-Git @('rev-parse', '--short=6', 'HEAD')
    if ($hash) { $version = $hash } else { $version = 'unknown' }
}

$status = Run-Git @('status', '--porcelain')
if ($status) { $version += '-dirty' }

# C string escaping (tags may contain quotes/backslashes in theory).
$escaped = $version.Replace('\', '\\').Replace('"', '\"')

$content = @"
/* Generated by tools/gen-shell-version.ps1 at build time - do not edit. */
#ifndef SHELL_VERSION_H
#define SHELL_VERSION_H
#define SHELL_COMMIT_VERSION "$escaped"
#endif
"@

$dir = Split-Path -Parent $OutFile
if ($dir -and -not (Test-Path $dir)) {
    New-Item -ItemType Directory -Force $dir | Out-Null
}

# Do not touch the file when nothing changed: every source that includes it
# would otherwise recompile on each build.
$old = if (Test-Path $OutFile) { Get-Content $OutFile -Raw } else { $null }
if ($old -ne ($content + "`n")) {
    Set-Content -Path $OutFile -Value $content -Encoding ASCII
}
